// Render the shipped UI with the local sample-paper fixture for store screenshots.
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = fileURLToPath(new URL('../docs/store/', import.meta.url));
const executablePath = [process.env.CHROME_PATH,
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  '/usr/bin/chromium', '/usr/bin/google-chrome',
].filter(Boolean).find(existsSync);
assert.ok(executablePath, 'Install Chrome / Edge or set CHROME_PATH');
await mkdir(output, { recursive: true });
const port = Number(process.env.SR_TEST_PORT || 8130);
const server = spawn(process.execPath, ['tools/serve.mjs', String(port)],
  { cwd: root, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
let browser;
try {
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Preview server timed out')), 10000);
    server.once('error', (error) => { clearTimeout(timeout); reject(error); });
    server.stderr.once('data', (data) => { clearTimeout(timeout); reject(new Error(String(data))); });
    server.stdout.once('data', () => { clearTimeout(timeout); resolve(); });
  });
  browser = await chromium.launch({ executablePath, headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(`http://localhost:${port}/test/fixture.html`);
  await page.waitForSelector('.sr-highlight-metrics');
  await page.evaluate(() => {
    const headings = document.querySelectorAll('h1');
    headings[0].textContent = 'Scholar Rank · Profile overview';
    headings[1].hidden = true;
    document.querySelectorAll('p.note').forEach((node) => { node.hidden = true; });
    document.querySelector('#gs_res_ccl_mid').hidden = true;
    const demo = document.createElement('p');
    demo.style.cssText = 'color:#64748b;margin:4px 0 22px;font-size:12px';
    demo.textContent = 'Local demo with sample papers · Rankings and author statistics generated by Scholar Rank';
    headings[0].after(demo);
  });
  await page.addStyleTag({ content: 'body{max-width:900px} #gsc_rsb{top:24px;right:24px;width:280px} #gsc_rsb_st,#gsc_g,.gsc_rsb_h{display:none} #gsc_a_b{width:900px} .gsc_a_at{font-size:14px} #gsc_a_b td{padding:11px 4px}' });
  await page.screenshot({ path: output + 'profile.png' });

  await page.goto(`http://localhost:${port}/test/fixture.html?theme=outline`);
  await page.waitForSelector('#gs_res_ccl_mid .sr-badges');
  await page.evaluate(() => {
    document.querySelector('#gsc_rsb').hidden = true;
    document.querySelector('#gsc_a_b').hidden = true;
    document.querySelectorAll('p.note, h1').forEach((node) => { node.hidden = true; });
    const heading = document.createElement('h1');
    heading.textContent = 'Scholar Rank · Search result badges';
    const note = document.createElement('p');
    note.style.cssText = 'color:#64748b;font-size:12px';
    note.textContent = 'Local demo with sample papers · Journal and conference ratings, indexing, impact factors, and preprints';
    const results = document.querySelector('#gs_res_ccl_mid');
    results.before(heading, note);
    const cards = results.querySelectorAll('.gs_r');
    cards.forEach((node, index) => { if (index >= 5) node.hidden = true; });
    results.querySelectorAll('.gs_rs').forEach((node) => node.remove());
  });
  await page.addStyleTag({ content: 'body{max-width:1180px;margin:28px 42px} h1{font-size:20px} .gs_r{margin:28px 0 36px;padding-bottom:18px;border-bottom:1px solid #e5e7eb} .gs_rt{font-size:18px;font-weight:400;color:#1a0dab;margin-bottom:8px} .gs_a{font-size:13px;color:#666} .sr-badges{margin:9px 0}' });
  await page.screenshot({ path: output + 'search.png' });

  await page.goto(`http://localhost:${port}/src/options/options.html?shim=1`);
  await page.waitForSelector('.theme-card');
  await page.locator('#themeGrid').evaluate((node) => node.closest('section').scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: output + 'settings.png' });
  assert.deepEqual(errors, [], 'Store preview has no runtime errors');
  console.log(`Store screenshots: ${output}`);
} finally {
  await browser?.close();
  server.kill();
}
